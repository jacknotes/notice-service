// buildVersion 构建版本标识（可用 -ldflags "-X main.buildVersion=..." 覆盖）。
var buildVersion = "dev"

// heartbeatInterval 实例心跳上报间隔（「信号在线」多节点健康）。
const heartbeatInterval = 5 * time.Second

// usageText 程序用法说明（--help 时打印）。
const usageText = `Usage: notice-service [options] [command]

Options:
  --config <path>   配置文件路径（默认 /etc/notice-service/config.yml）
  -h, --help        显示本帮助并退出
  -v, --version     显示构建版本并退出

Commands:
  reset-password    离线重置指定用户密码（并清除其双因子认证）：
                    notice-service reset-password --username <name> --new-password <pw>
`

// handleCLIArgs 处理纯 CLI 参数（--help/-h/--version/-v/未知参数）。
// 返回 (exitCode, handled)：handled=true 表示已处理并应退出（不启动服务）；
// handled=false 表示是正常启动参数（无参数 / --config / reset-password），继续往下走。
// 必须在任何副作用（加载配置/连库/监听端口/注册心跳）之前调用。
func handleCLIArgs(args []string, stdout, stderr io.Writer) (int, bool) {
	if len(args) == 0 {
		return 0, false // 无参数 → 正常启动
	}
	first := args[0]
	switch first {
	case "-h", "--help":
		fmt.Fprint(stdout, usageText)
		return 0, true
	case "-v", "--version":
		fmt.Fprintf(stdout, "notice-service %s\n", buildVersion)
		return 0, true
	case "reset-password", "--config":
		return 0, false // 由后续逻辑处理
	}
	if strings.HasPrefix(first, "--config=") {
		return 0, false
	}
	// 未知参数：报错并提示用法，避免误启动完整服务
	fmt.Fprintf(stderr, "未知参数: %s\n", first)
	fmt.Fprint(stderr, usageText)
	return 2, true
}

func main() {
	// 纯 CLI 参数（--help/-h/--version/-v）在任何副作用（加载配置/连库/监听）之前处理：
	// 避免 --help 误触发完整启动流程——连库、注册心跳、监听端口后 bind 失败退出，
	// 却在 DB 遗留僵尸心跳节点（前端多显示一个离线节点）。未知参数同样提前报错退出。
	if code, handled := handleCLIArgs(os.Args[1:], os.Stdout, os.Stderr); handled {
		os.Exit(code)
	}

	cfg := config.Load()

	// Gin 模式：GIN_MODE 环境变量优先（debug/release/test），默认 release。
	// 必须在创建 engine（router.NewRouter）之前设置，否则启动横幅/请求日志按错误模式输出。
	mode := os.Getenv("GIN_MODE")
	if mode == "" {
		mode = gin.ReleaseMode
	}
	gin.SetMode(mode)

	// reset-password 子命令：唯一 admin 忘记密码时离线重置，不启动 HTTP 服务。
	if len(os.Args) > 1 && os.Args[1] == "reset-password" {
		os.Exit(runResetPasswordCmd(cfg))
	}

	// 弱默认密钥告警：防止以默认/示例密钥裸跑
	for _, w := range cfg.WeakSecretWarnings() {
		log.Printf("[警告] %s", w)
	}

	db, err := database.Open(cfg.DSN())
	if err != nil {
		log.Fatalf("db connect: %v", err)
	}
	defer db.Close()
	if err := database.Migrate(db); err != nil {
		log.Fatalf("migrate: %v", err)
	}

	// R3：自动生成密钥 + 库里已有密文 → 拒绝启动，防静默丢失历史渠道配置。
	if err := checkEncryptKeyPresence(cfg, repository.NewChannelRepo(db)); err != nil {
		log.Fatalf("启动中止: %v", err)
	}

	if cfg.EncryptKeyAutoGenerated {
		// 首启（无任何历史密文）：密钥为自动生成，提示运维立即持久化，防止下次重启密钥变化导致历史渠道配置不可解。
		log.Printf("[警告] 未设置 ENCRYPT_KEY 且未找到密钥文件，已自动生成新密钥并写入 %s。请立即持久化该密钥（设置 ENCRYPT_KEY 环境变量或备份该文件），否则下次重启将无法解密历史渠道配置。", cfg.EncryptKeyFile)
	}

	ciph, err := crypto.New([]byte(padKey(cfg.EncryptKey)))
	if err != nil {
		log.Fatalf("crypto: %v", err)
	}

	authSvc := service.NewAuthService(db, cfg.JWTSecret, cfg.AdminUser, cfg.AdminPass)
	if err := authSvc.BootstrapAdmin(); err != nil {
		log.Fatalf("bootstrap admin: %v", err)
	}

	ns := service.NewNotificationService(db, ciph)

	// 发送队列：入队即落库，worker 池后台消费（重试/崩溃接管/清理都在这层）
	qcfg := service.QueueConfig{
		Workers:            cfg.QueueWorkers,
		PollInterval:       time.Duration(cfg.QueuePollMS) * time.Millisecond,
		MaxAttempts:        cfg.QueueMaxAttempts,
		RetryBackoff:       cfg.QueueRetryBackoff,
		ClaimTTL:           cfg.QueueClaimTTL,
		LogRetentionDays:   cfg.LogRetentionDays,
		JobRetentionDays:   cfg.QueueJobRetentionDays,
		AuditRetentionDays: cfg.AuditRetentionDays,
	}
	queue := service.NewQueueService(db, ns, qcfg, cfg.InstanceID)
	queue.Start()
	defer queue.StopWithTimeout(15 * time.Second)

	// 注入 /metrics 的队列深度指标（scrape 时实时统计 pending job 数）。
	metrics.QueuePendingFunc = func() float64 {
		n, err := repository.NewSendJobRepo(db).CountPending()
		if err != nil {
			return 0
		}
		return float64(n)
	}

	// 调度器：cron 到点只做快速入队（毫秒级），带 dedupe key 防极端竞态重复
	sched := scheduler.New(func(taskID int64, dedupeKey string) {
		if _, err := queue.Enqueue(taskID, nil, dedupeKey,
			service.Trigger{Type: "cron", By: "scheduler"}); err != nil {
			log.Printf("scheduler: enqueue task %d failed: %v", taskID, err)
		}
	}, repository.NewTaskRepo(db), cfg.InstanceID)
	sched.Start()
	defer sched.Stop()
	tasks, err := repository.NewTaskRepo(db).ListEnabledCron()
	if err != nil {
		log.Fatalf("load cron tasks: %v", err)
	}
	for _, t := range tasks {
		sched.RegisterTask(t.ID, t.CronExpr)
	}

	// 实例心跳：周期上报自身节点信息，供「信号在线」查看多后端健康；
	// 优雅退出时删除本实例心跳，避免遗留僵尸节点。
	hbRepo := repository.NewHeartbeatRepo(db)
	host, _ := os.Hostname()
	// 启动即清理同主机同端口的历史心跳（仅保留当前实例）。本地反复重启/被强杀
	// 时旧实例行会残留，造成「节点列表显示多个、实际只跑一个」的假象。
	if err := hbRepo.PurgeSameAddr(host, cfg.Port, cfg.InstanceID); err != nil {
		log.Printf("heartbeat: purge stale instances: %v", err)
	}
	startedAt := time.Now()
	hbCtx, hbCancel := context.WithCancel(context.Background())
	var hbWG sync.WaitGroup
	hbWG.Add(1)
	go func() {
		defer hbWG.Done()
		tick := func() {
			_ = hbRepo.Upsert(&repository.Instance{
				InstanceID: cfg.InstanceID, Host: host, Port: cfg.Port, Version: buildVersion,
				StartedAt: startedAt, LastSeenAt: time.Now(),
			})
		}
		tick() // 启动立即上报一次
		ticker := time.NewTicker(heartbeatInterval)
		defer ticker.Stop()
		for {
			select {
			case <-hbCtx.Done():
				_ = hbRepo.Remove(cfg.InstanceID)
				return
			case <-ticker.C:
				tick()
			}
		}
	}()
	defer func() {
		hbCancel()
		hbWG.Wait()
	}()

	engine := router.NewRouter(db, authSvc, ciph, sched, queue, router.Options{
		TrustedProxies:  cfg.TrustedProxies,
		SwaggerEnabled:  cfg.SwaggerEnabled,
		MetricsEnabled:  cfg.MetricsEnabled,
		MetricsUser:     cfg.MetricsUser,
		MetricsPassword: cfg.MetricsPassword,
		BuildVersion:    buildVersion,
		InstanceID:      cfg.InstanceID,
	})
	staticDir, staticOK := resolveStaticDir(cfg.StaticDir)
	if staticOK {
		engine.Static("/assets", filepath.Join(staticDir, "assets"))
		engine.StaticFile("/", filepath.Join(staticDir, "index.html"))
	} else {
		log.Printf("[警告] 未找到静态资源目录（STATIC_DIR=%s，./web/dist，可执行文件同目录均不存在），SPA 页面不可用，API 照常。", cfg.StaticDir)
	}
	engine.NoRoute(func(c *gin.Context) {
		if strings.HasPrefix(c.Request.URL.Path, "/api/") {
			c.JSON(404, gin.H{"error": "not found"})
			return
		}
		if staticOK && c.Request.Method == "GET" {
			c.File(filepath.Join(staticDir, "index.html"))
			return
		}
		c.JSON(404, gin.H{"error": "not found"})
	})

	// 生产级 HTTP 服务器：读/写/空闲超时防慢连接与连接耗尽。
	srv := &http.Server{
		Addr:              ":" + cfg.Port,
		Handler:           engine,
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       10 * time.Second,
		WriteTimeout:      20 * time.Second,
		IdleTimeout:       60 * time.Second,
	}

	// 优雅退出：SIGINT/SIGTERM → 停止接收新连接 → 等待在途请求完成 →
	// 排空发送队列（defer queue.Stop 会在返回后执行）→ 停调度器 → 关 DB。
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	go func() {
		<-ctx.Done()
		log.Printf("收到退出信号，开始优雅关闭（最多 15s）...")
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		defer cancel()
		if err := srv.Shutdown(shutdownCtx); err != nil {
			log.Printf("http shutdown: %v", err)
		}
	}()

	log.Printf("notice-service listening on :%s (build %s) (instance %s)", cfg.Port, buildVersion, cfg.InstanceID)
	if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
		// 启动失败（典型：端口被占用 bind error）：心跳 goroutine 已在 bind 前上报过
		// 本实例，此处必须清理，否则 DB 遗留僵尸心跳 → 前端多显示一个离线节点。
		// log.Fatal 会跳过上方 defer（含心跳清理），故先显式取消心跳并删除本实例行。
		hbCancel()
		hbWG.Wait()
		if err2 := hbRepo.Remove(cfg.InstanceID); err2 != nil {
			log.Printf("heartbeat: cleanup on startup failure: %v", err2)
		}
		log.Fatal(err)
	}
}

// runResetPasswordCmd 处理 reset-password 子命令，返回进程退出码。
func runResetPasswordCmd(cfg *config.Config) int {
	username := cfg.AdminUser
	newPassword := ""
	fs := flag.NewFlagSet("reset-password", flag.ContinueOnError)
	fs.StringVar(&username, "username", cfg.AdminUser, "要重置的用户名（默认 ADMIN_USER）")
	fs.StringVar(&newPassword, "new-password", "", "新密码（缺省时交互式输入，不回显）")
	if err := fs.Parse(os.Args[2:]); err != nil {
		return 2
	}
	if newPassword == "" {
		pw, err := promptNewPassword(os.Stdin, os.Stdout)
		if err != nil {
			fmt.Fprintln(os.Stderr, "读取密码失败:", err)
			return 2
		}
		newPassword = pw
	}
	db, err := database.Open(cfg.DSN())
	if err != nil {
		fmt.Fprintln(os.Stderr, "数据库连接失败:", err)
		return 1
	}
	defer db.Close()
	if err := resetPassword(db, username, newPassword); err != nil {
		fmt.Fprintln(os.Stderr, "重置失败:", err)
		return 1
	}
	fmt.Printf("已重置用户 %s 的密码\n", username)
	return 0
}

// checkEncryptKeyPresence 若密钥为自动生成（无 ENCRYPT_KEY 且无密钥文件）而库里已有
// 加密渠道配置，返回错误（应拒绝启动，防静默丢失历史配置）。注意：此分支还会移除
// 本次自动生成的无效密钥文件，防止下次启动误认其为有效密钥而静默用错密钥启动。
func checkEncryptKeyPresence(cfg *config.Config, chRepo *repository.ChannelRepo) error {
	if !cfg.EncryptKeyAutoGenerated {
		return nil
	}
	n, err := chRepo.CountEncrypted()
	if err != nil {
		return err
	}
	if n > 0 {
		_ = os.Remove(cfg.EncryptKeyFile) // 移除无效密钥，确保下次启动仍会触发本校验
		return fmt.Errorf("检测到 %d 个已加密渠道配置，但未提供 ENCRYPT_KEY 且密钥文件 %s 无法解密历史配置（本次自动生成的新密钥已移除），历史渠道配置将无法解密；请设置 ENCRYPT_KEY 或恢复原密钥文件", n, cfg.EncryptKeyFile)
	}
	return nil
}

// resolveStaticDir 按优先级解析静态资源目录：配置值 → ./web/dist → 可执行文件同目录 web/dist。
// 返回 (目录, 是否可用)。
func resolveStaticDir(configured string) (string, bool) {
	for _, d := range []string{configured, "./web/dist"} {
		if d != "" && dirExists(d) {
			return d, true
		}
	}
	if exe, err := os.Executable(); err == nil {
		if cand := filepath.Join(filepath.Dir(exe), "web", "dist"); dirExists(cand) {
			return cand, true
		}
	}
	return "", false
}

func dirExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && st.IsDir()
}

// padKey 保证 32 字节：过长截断，过短用 SHA-256 摘要补齐。
func padKey(s string) string {
	if len(s) >= 32 {
		return s[:32]
	}
	sum := sha256.Sum256([]byte(s))
	return string(sum[:])
}
